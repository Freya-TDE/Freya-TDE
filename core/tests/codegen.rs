//! Code generation: project layout, determinism, user files, Cargo.toml
//! merging, diagnostics and writing.

use std::collections::BTreeMap;
use std::path::PathBuf;

use tdr_core::codegen::{Change, CodegenIssue, FileKind, Generation, WriteError, generate, write};
use tdr_core::pack::load_all;
use tdr_core::*;

fn name(n: &str) -> ComponentName {
    ComponentName::new(n).unwrap()
}

fn handler(n: &str) -> HandlerName {
    HandlerName::new(n).unwrap()
}

/// Core types plus all packs from `components/`.
fn registry() -> TypeRegistry {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../components");
    let (packs, errors) = load_all(&dir);
    assert!(errors.is_empty(), "{errors:#?}");
    let mut registry = TypeRegistry::with_builtins();
    for pack in &packs {
        pack.register(&mut registry).unwrap();
    }
    registry
}

fn project() -> ProjectFile {
    ProjectFile::new("crm", "1.99", "egui").unwrap()
}

/// services (data module): runtime, db_pool
/// main_form (form):       window with ok/name widgets, api router, load query
fn forms() -> Vec<Form> {
    let mut services = Form::data_module(name("services"), "egui");
    services
        .add_component(Component::new(
            name("runtime"),
            TypeRef::pack("tokio", "Runtime"),
        ))
        .unwrap();
    services
        .add_component(
            Component::new(name("db_pool"), TypeRef::pack("sqlx", "Pool"))
                .with("url", "postgres://localhost/crm")
                .with("max_connections", 8i64),
        )
        .unwrap();

    let mut main = Form::new(
        name("main_form"),
        "egui",
        Widget::from_component(
            Component::new(name("window"), builtin::form()).on("on_close", handler("may_close")),
        ),
    );
    main.add_widget(
        &name("window"),
        Widget::from_component(
            Component::new(name("ok_button"), builtin::button())
                .on("on_click", handler("ok_clicked")),
        ),
    )
    .unwrap();
    main.add_widget(
        &name("window"),
        Widget::from_component(
            Component::new(name("name_edit"), builtin::edit())
                .on("on_change", handler("name_changed")),
        ),
    )
    .unwrap();
    main.add_component(
        Component::new(name("api"), TypeRef::pack("axum", "Router")).with(
            "pool",
            Value::reference_on(name("services"), name("db_pool")),
        ),
    )
    .unwrap();
    main.add_component(
        Component::new(name("load"), TypeRef::pack("sqlx", "Query"))
            .with(
                "pool",
                Value::reference_on(name("services"), name("db_pool")),
            )
            .with("router", Value::reference(name("api")))
            .with("sql", Value::Code("\"SELECT * FROM customers\"".into())),
    )
    .unwrap();
    vec![services, main]
}

fn empty() -> BTreeMap<String, String> {
    BTreeMap::new()
}

fn errors(generation: &Generation) -> Vec<String> {
    generation
        .diagnostics
        .iter()
        .map(ToString::to_string)
        .collect()
}

fn content<'g>(generation: &'g Generation, path: &str) -> &'g str {
    &generation
        .file(path)
        .unwrap_or_else(|| panic!("{path} not generated"))
        .content
}

#[test]
fn generates_the_project_layout() {
    let generation = generate(&project(), &forms(), &registry(), &empty());
    assert!(
        generation.diagnostics.is_empty(),
        "{:#?}",
        errors(&generation)
    );

    let files: Vec<(&str, FileKind, Change)> = generation
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.kind, f.change))
        .collect();
    assert_eq!(
        files,
        [
            ("Cargo.toml", FileKind::Manifest, Change::Create),
            ("src/main.rs", FileKind::User, Change::Create),
            ("src/app.gen.rs", FileKind::Generated, Change::Create),
            ("src/services.gen.rs", FileKind::Generated, Change::Create),
            ("src/services.rs", FileKind::User, Change::Create),
            ("src/main_form.gen.rs", FileKind::Generated, Change::Create),
            ("src/main_form.rs", FileKind::User, Change::Create),
        ]
    );

    // Dependencies first.
    let order: Vec<String> = generation.order.iter().map(ToString::to_string).collect();
    assert_eq!(
        order,
        [
            "services::runtime",
            "services::db_pool",
            "main_form::api",
            "main_form::load"
        ]
    );

    let app = content(&generation, "src/app.gen.rs");
    assert!(app.starts_with("// @generated by Freya-TD"));
    assert!(
        app.contains("#[tokio::main(flavor = \"multi_thread\")]"),
        "{app}"
    );
    assert!(app.contains("pub async fn init() -> Result<Self, Error>"));
    assert!(app.contains(".max_connections(8)"));
    assert!(app.contains(".connect(\"postgres://localhost/crm\")"));
    assert!(app.contains("axum::Router::new().with_state(services__db_pool.clone())"));
    assert!(app.contains(
        "let main_form__load = (services__db_pool.clone(), \"SELECT * FROM customers\");"
    ));
    assert!(app.contains("#[path = \"main_form.rs\"]"));

    let form = content(&generation, "src/main_form.gen.rs");
    assert!(form.contains("pub struct MainForm"));
    assert!(
        form.contains("pub load: (sqlx::PgPool, &'static str),"),
        "{form}"
    );

    // Handler stubs with the event signatures.
    let user = content(&generation, "src/main_form.rs");
    assert!(user.contains("include!(\"main_form.gen.rs\");"));
    assert!(
        user.contains("pub fn may_close(&mut self) -> bool {"),
        "{user}"
    );
    assert!(user.contains("todo!(\"may_close\")"));
    assert!(user.contains("pub fn ok_clicked(&mut self) {}"));
    assert!(user.contains("pub fn name_changed(&mut self, text: &str) {}"));

    let main = content(&generation, "src/main.rs");
    assert!(main.contains("async fn started(app: app::App) -> Result<(), app::Error>"));

    let cargo = content(&generation, "Cargo.toml");
    assert!(cargo.contains("name = \"crm\""));
    assert!(cargo.contains("rust-version = \"1.99\""));
    assert!(cargo.contains("axum = \"0.8\""), "{cargo}");
    assert!(cargo.contains(
        "sqlx = { version = \"0.9\", features = [\"macros\", \"postgres\", \"runtime-tokio\"] }"
    ));
}

#[test]
fn output_is_deterministic() {
    let a = generate(&project(), &forms(), &registry(), &empty());
    let b = generate(&project(), &forms(), &registry(), &empty());
    assert_eq!(a, b);
}

#[test]
fn user_files_are_kept_and_only_missing_stubs_appended() {
    let mut files = empty();
    let own = "//! My form.\n\ninclude!(\"main_form.gen.rs\");\n\nimpl MainForm {\n    // my own code\n    pub fn ok_clicked(&mut self) {\n        println!(\"ok\");\n    }\n}\n";
    files.insert("src/main_form.rs".into(), own.into());
    files.insert(
        "src/main.rs".into(),
        "mod app;\nfn main() {}\nasync fn started(app: app::App) -> Result<(), app::Error> { Ok(()) }\n".into(),
    );
    let generation = generate(&project(), &forms(), &registry(), &files);
    assert!(
        generation.diagnostics.is_empty(),
        "{:#?}",
        errors(&generation)
    );

    let file = generation.file("src/main_form.rs").unwrap();
    assert_eq!(file.change, Change::Update);
    // The user's text is untouched, the missing stubs follow.
    assert!(file.content.starts_with(own));
    let added = &file.content[own.len()..];
    assert!(added.contains("impl MainForm {"));
    assert!(added.contains("pub fn may_close(&mut self) -> bool"));
    assert!(added.contains("pub fn name_changed(&mut self, text: &str)"));
    assert!(!added.contains("ok_clicked"));

    // main.rs is never touched.
    assert_eq!(
        generation.file("src/main.rs").unwrap().change,
        Change::Unchanged
    );
}

#[test]
fn cargo_toml_is_merged_not_replaced() {
    let mut files = empty();
    files.insert(
        "Cargo.toml".into(),
        "[package]\nname = \"crm\"\nversion = \"0.3.0\"\nedition = \"2024\"\n\n[dependencies]\n# logging\nlog = \"0.4\"\ntokio = \"1\"\n".into(),
    );
    let generation = generate(&project(), &forms(), &registry(), &files);
    let cargo = content(&generation, "Cargo.toml");
    assert!(cargo.contains("# logging\nlog = \"0.4\""), "{cargo}");
    assert!(cargo.contains("version = \"0.3.0\""));
    // The user's version stays, the features are added.
    assert!(
        cargo.contains("tokio = { version = \"1\", features = [\"macros\", \"rt-multi-thread\"] }"),
        "{cargo}"
    );
    assert!(generation.diagnostics.iter().any(|d| matches!(
        &d.issue,
        CodegenIssue::CargoVersionDiffers { crate_name, project, required }
            if crate_name == "tokio" && project == "1" && required == "1.54"
    )));
    assert!(!generation.has_errors());
}

#[test]
fn async_init_needs_a_runtime() {
    let mut forms = forms();
    forms[0].remove(&name("runtime")).unwrap();
    let generation = generate(&project(), &forms, &registry(), &empty());
    assert!(generation.has_errors());
    let pool = "services::db_pool".parse().unwrap();
    assert!(
        generation
            .diagnostics
            .iter()
            .any(|d| d.issue == CodegenIssue::AsyncWithoutRuntime
                && d.element.as_ref() == Some(&pool))
    );
    // Without a runtime, init and started are synchronous.
    assert!(
        content(&generation, "src/app.gen.rs").contains("pub fn init() -> Result<Self, Error>")
    );
}

#[test]
fn handler_conflicts_are_reported() {
    let mut forms = forms();
    // on_click() and on_change(text: &str) on the same handler.
    forms[1]
        .element_mut(&name("name_edit"))
        .unwrap()
        .events
        .insert("on_change".into(), handler("ok_clicked"));
    let generation = generate(&project(), &forms, &registry(), &empty());
    let conflict = generation
        .diagnostics
        .iter()
        .find_map(|d| match &d.issue {
            CodegenIssue::HandlerConflict { handler, events } => Some((handler, events)),
            _ => None,
        })
        .expect("conflict reported");
    assert_eq!(conflict.0.as_str(), "ok_clicked");
    assert_eq!(conflict.1, &["ok_button.on_click", "name_edit.on_change"]);
}

#[test]
fn template_errors_name_component_and_part() {
    let mut registry = registry();
    registry
        .register(
            ComponentType::new(TypeRef::pack("demo", "Broken"), TypeKind::NonVisual).with_codegen(
                CodegenSpec {
                    rust_type: "u32".into(),
                    init: "{{ props.missing }}".into(),
                    is_async: false,
                    share: ShareMode::Clone,
                    entry: None,
                },
            ),
        )
        .unwrap();
    let mut forms = forms();
    forms[0]
        .add_component(Component::new(
            name("broken"),
            TypeRef::pack("demo", "Broken"),
        ))
        .unwrap();
    let generation = generate(&project(), &forms, &registry, &empty());
    let diagnostic = generation
        .diagnostics
        .iter()
        .find(|d| matches!(d.issue, CodegenIssue::Template { .. }))
        .expect("template error");
    assert_eq!(
        diagnostic.element,
        Some("services::broken".parse().unwrap())
    );
    assert!(
        matches!(&diagnostic.issue, CodegenIssue::Template { part, line: Some(1), .. } if part == "init")
    );
}

#[test]
fn diagnostics_serialize_with_stable_codes() {
    let mut forms = forms();
    forms[0].remove(&name("runtime")).unwrap();
    let generation = generate(&project(), &forms, &registry(), &empty());
    let json = serde_json::to_value(&generation.diagnostics).unwrap();
    let codes: Vec<&str> = json
        .as_array()
        .unwrap()
        .iter()
        .map(|d| d["issue"]["code"].as_str().unwrap())
        .collect();
    assert!(codes.contains(&"async_without_runtime"), "{codes:?}");
    // Graph findings keep their own code inside `project`.
    let project = json
        .as_array()
        .unwrap()
        .iter()
        .find(|d| d["issue"]["code"] == "project")
        .unwrap();
    assert_eq!(project["issue"]["detail"]["code"], "unsatisfied");
    assert_eq!(project["severity"], "error");
    // Files serialize too (without the previous content).
    let file = serde_json::to_value(&generation.files[0]).unwrap();
    assert_eq!(file["change"], "create");
    assert!(file.get("previous").is_none());
}

#[test]
fn write_then_regenerate_is_unchanged() {
    let dir = std::env::temp_dir().join(format!("tdr-codegen-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    let (project, forms, registry) = (project(), forms(), registry());

    let generation = generate(&project, &forms, &registry, &dir);
    let written = write(&dir, &generation).unwrap();
    assert_eq!(written.len(), 7);

    let again = generate(&project, &forms, &registry, &dir);
    assert!(again.files.iter().all(|f| f.change == Change::Unchanged));
    assert_eq!(write(&dir, &again).unwrap(), Vec::<String>::new());

    // A stale generation never overwrites a file edited meanwhile.
    let mut forms2 = forms.clone();
    forms2[1]
        .element_mut(&name("ok_button"))
        .unwrap()
        .events
        .insert("on_click".into(), handler("ok_pressed"));
    let stale = generate(&project, &forms2, &registry, &dir);
    std::fs::write(dir.join("src/main_form.rs"), "// edited\n").unwrap();
    assert_eq!(
        write(&dir, &stale),
        Err(WriteError::Modified("src/main_form.rs".into()))
    );
    assert_eq!(
        std::fs::read_to_string(dir.join("src/main_form.rs")).unwrap(),
        "// edited\n"
    );
    std::fs::remove_dir_all(&dir).unwrap();
}

#[test]
fn errors_block_writing() {
    let mut forms = forms();
    forms[0].remove(&name("runtime")).unwrap();
    let generation = generate(&project(), &forms, &registry(), &empty());
    assert!(matches!(
        write(&std::env::temp_dir(), &generation),
        Err(WriteError::HasErrors(_))
    ));
}
